# Main translation entry point -------------------------------------------------

#' Translate and display an R help page in Chinese
#'
#' @param topic A name or character string specifying the help topic.
#' @param package Optional package name. If `NULL`, loaded packages are searched.
#' @param lang Target language. Defaults to the value set via [deephelp_use()].
#' @param type Output type: `"html"` (default, opens the translated page in the
#'   Help pane of RStudio or Positron) or `"text"` (prints plain text).
#' @param ... Currently ignored.
#' @export
deephelp <- function(topic, package = NULL, lang = NULL, type = NULL, ...) {
  tryCatch(
    deephelp_impl(topic, package, lang, type, ...),
    error = function(e) {
      warning("deephelp: ", conditionMessage(e),
              " Falling back to the original (English) help.", call. = FALSE)
      if (is.null(package)) {
        utils::help(topic)
      } else {
        # do.call() so utils::help() receives the *value* of `package`, not the
        # symbol `package` (its substitute()-based unquoted-name detection would
        # otherwise misread it as the package named "package").
        do.call(utils::help, list(topic = topic, package = package))
      }
    }
  )
}

deephelp_impl <- function(topic, package = NULL, lang = NULL, type = NULL, ...) {
  cfg <- .dh$config
  if (is.null(lang)) {
    lang <- cfg$lang
  }

  info <- rd_find(topic, package)
  cache_file_path <- cache_path(info, cfg)
  rd <- cache_read(cache_file_path)

  if (is.null(rd)) {
    message("deephelp: translating '", info$topic, "' from package '",
            info$package, "' to ", lang, " ...")
    rd <- rd_get_parsed(info)
    rd <- rd_translate(rd, lang, cfg)
    cache_write(cache_file_path, rd)
  }

  structure(
    list(topic = info$topic, package = info$package, rd = rd,
         type = type %||% "html"),
    class = "deephelp_topic"
  )
}

# Serialize a parsed Rd object back to Rd source text (used to show the
# translated help in the Help pane via rstudioapi::previewRd()).
#
# tools:::as.character.Rd() is an unexported base tool; utils::getFromNamespace()
# retrieves it at runtime without the ':::' operator in the source.
rd_to_source <- function(rd) {
  as_character_Rd <- utils::getFromNamespace("as.character.Rd", "tools")
  src <- paste(as_character_Rd(rd, deparse = TRUE), collapse = "")
  # Rebuilt Rd nodes lose their srcref, so as.character.Rd() can deparse an
  # unbraced \item (itemize bullet) as "\itemText" with no separator, which the
  # parser then reads as an unknown macro. Restore the separating space (but not
  # after \itemize).
  gsub("\\\\item(?!ize)(?=[A-Za-z0-9])", "\\\\item ", src, perl = TRUE)
}

# Write a translated Rd object into a minimal fake package layout
# (<root>/<pkg>/man/<topic>.Rd + <root>/<pkg>/DESCRIPTION) and return the Rd
# file path, or NULL when no package context is available.
#
# rstudioapi::previewRd() renders a standalone .Rd file with `package = ""`,
# which makes tools::Rd2HTML() emit broken relative links for unqualified
# \link{topic} macros (e.g. "../..//help/aov") and, in turn, RStudio fails to
# navigate when they are clicked ("/help/preview?file=... not found"). RStudio's
# preview renderer detects a package by looking for DESCRIPTION two levels above
# the Rd file; providing one makes it render with `package = <pkg>`, so
# \link{topic} links become "/library/<pkg>/help/<topic>" and jump to the real
# (original-language) help page.
preview_rd_in_help <- function(rd, topic, package) {
  if (is.null(package) || !nzchar(package)) {
    return(NULL)
  }

  root <- tempfile("deephelp_")
  pkg_dir <- file.path(root, sanitize(package))
  man_dir <- file.path(pkg_dir, "man")

  dir.create(man_dir, recursive = TRUE, showWarnings = FALSE)
  if (!dir.exists(man_dir)) {
    return(NULL)
  }

  topic_name <- if (is.null(topic) || !nzchar(topic)) "topic" else topic
  rd_file <- file.path(man_dir, paste0(sanitize(topic_name), ".Rd"))

  ok <- tryCatch({
    writeLines(rd_to_source(rd), rd_file, useBytes = TRUE)
    writeLines(c(
      paste0("Package: ", package),
      "Version: 0.0.0",
      "Title: deephelp preview",
      "Description: Generated by deephelp to preview a translated help page.",
      "License: MIT",
      "Type: Package"
    ), file.path(pkg_dir, "DESCRIPTION"), useBytes = TRUE)
    TRUE
  }, error = function(e) FALSE)

  if (!ok || !file.exists(rd_file)) {
    return(NULL)
  }
  rd_file
}

#' @export
print.deephelp_topic <- function(x, ...) {
  # "text" type always prints plain text.
  if (!identical(x$type, "html")) {
    tools::Rd2txt(x$rd)
    return(invisible(x))
  }

  # Preview the translated Rd in the Help pane (works in both RStudio and
  # Positron). A minimal fake package layout is used so the host can resolve
  # \link{...} cross-references for the page being shown.
  if (requireNamespace("rstudioapi", quietly = TRUE) &&
      rstudioapi::isAvailable() &&
      rstudioapi::hasFun("previewRd")) {
    rd_file <- preview_rd_in_help(x$rd, x$topic, x$package)
    if (!is.null(rd_file) && file.exists(rd_file)) {
      rstudioapi::previewRd(rd_file)
      return(invisible(x))
    }
  }

  # Outside RStudio/Positron: fall back to plain text.
  tools::Rd2txt(x$rd)
  invisible(x)
}

rd_find <- function(topic, package = NULL) {
  h <- if (is.null(package)) {
    utils::help(topic, help_type = "text")
  } else {
    # do.call() passes the value of `package`, avoiding utils::help()'s
    # substitute()-based unquoted-name detection (which would read the symbol
    # `package` as the package literally named "package").
    do.call(utils::help, list(topic = topic, package = package, help_type = "text"))
  }
  paths <- as.character(h)
  if (length(paths) == 0L) {
    stop("No help found for '", topic, "'",
         if (is.null(package)) "" else paste0(" in package '", package, "'"),
         call. = FALSE)
  }
  path <- paths[[1L]]
  parts <- strsplit(path, "[\\/]", perl = TRUE)[[1L]]
  i_help <- which(parts == "help")
  pkg <- if (length(i_help) > 0L && i_help[[1L]] > 1L) {
    parts[i_help[[1L]] - 1L]
  } else {
    package
  }
  topic_file <- parts[length(parts)]
  version <- tryCatch(as.character(utils::packageVersion(pkg)),
                      error = function(e) "0")
  list(package = pkg, topic = topic_file, version = version)
}

rd_get_parsed <- function(info) {
  key <- paste0(info$package, "@", info$version)
  db <- .dh$rd_db[[key]]
  if (is.null(db)) {
    db <- tools::Rd_db(info$package)
    .dh$rd_db[[key]] <- db
  }
  rd <- db[[paste0(info$topic, ".Rd")]]
  if (is.null(rd)) {
    hits <- grep(paste0("^", info$topic, "\\.Rd$"), names(db),
                 ignore.case = TRUE, value = TRUE)
    if (length(hits) > 0L) {
      rd <- db[[hits[[1L]]]]
    }
  }
  if (is.null(rd)) {
    stop("Could not locate Rd source for '", info$topic, "' in package '",
         info$package, "'.", call. = FALSE)
  }
  rd
}

cache_path <- function(info, cfg) {
  if (!is.null(cfg$cache) && !nzchar(cfg$cache)) {
    return(NULL)
  }
  root <- if (is.null(cfg$cache)) tools::R_user_dir("deephelp", "cache") else cfg$cache
  file.path(
    root,
    sanitize(info$package),
    sanitize(info$topic),
    paste0(sanitize(info$version), "__", sanitize(cfg$model), "__",
           sanitize(cfg$lang), "__", .dh$schema, "__", config_hash(cfg), ".rds")
  )
}

sanitize <- function(x) {
  x <- gsub("[^A-Za-z0-9._-]", "_", x, perl = TRUE)
  if (!nzchar(x)) {
    x <- "_"
  }
  x
}

cache_read <- function(path) {
  if (is.null(path) || !file.exists(path)) {
    return(NULL)
  }
  tryCatch(readRDS(path), error = function(e) NULL)
}

cache_write <- function(path, rd) {
  if (is.null(path)) {
    return(invisible(FALSE))
  }
  # Drop environment-backed attributes that do not survive serialization and
  # are not needed for rendering (macros is only used for \Sexpr re-parsing).
  attr(rd, "macros") <- NULL
  attr(rd, "srcref") <- NULL
  attr(rd, "concordance") <- NULL
  dir.create(dirname(path), recursive = TRUE, showWarnings = FALSE)
  ok <- tryCatch({
    saveRDS(rd, path)
    TRUE
  }, error = function(e) FALSE)
  invisible(ok)
}
